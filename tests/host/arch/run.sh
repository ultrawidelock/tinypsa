# Builds and runs the Arm psa-arch-tests crypto suite against tinypsa on the host.
#   tests/host/arch/run.sh <psa-arch-tests checkout> <tinypsa host build dir> <mbedtls dir>
# Functions tinypsa does not provide link to stubs returning NOT_SUPPORTED.
set -eu
# The system toolchain, ahead of any shims on PATH; sub-builds inherit CC.
PATH=/usr/bin:$PATH
export CC=/usr/bin/cc
arch=$(cd "$1" && pwd) host=$(cd "$2" && pwd) mbedtls=$(cd "$3" && pwd)
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
out=$host/arch
tgt=$arch/api-tests/platform/targets/tgt_dev_apis_tinypsa
mkdir -p "$out"
rm -rf "$tgt"
cp -R "$arch/api-tests/platform/targets/tgt_dev_apis_stdc" "$tgt"
cp "$here/pal_crypto_config.h" "$tgt/nspe/pal_crypto_config.h"
# Tests our feature set compiles out leave unused variables behind.
sed -i.orig 's/ -Werror -Werror//' "$arch/api-tests/tools/cmake/compiler/HOST_GCC.cmake"
# Mach-O wants "segment,section" where ELF takes a bare section name.
if [ "$(uname)" = Darwin ]; then
	sed -i '' 's/section("\.acs_test_info")/section("__DATA,__acs_test_info")/' \
		"$arch/api-tests/val/common/val.h"
fi

libs="$host/libtinypsa_host.a $host/libtest_backend.a $host/libmbedtls_host.a"
cc_flags="-fsanitize=address,undefined"
build() {
	cmake -S "$arch/api-tests" -B "$out/build" -DTARGET=tgt_dev_apis_tinypsa \
		-DTOOLCHAIN=HOST_GCC -DSUITE=CRYPTO -DCMAKE_C_COMPILER=/usr/bin/cc \
		-DPSA_INCLUDE_PATHS="$here/include;$root/include;$mbedtls/include;$root/tests/host/backend_mbedtls/include;$root/tests/host" \
		-DPSA_CRYPTO_LIB_FILENAME="$out/libtinypsa_all.a" \
		-DCMAKE_EXE_LINKER_FLAGS="$cc_flags" >/dev/null
	cmake --build "$out/build" -j 8 >"$out/build.log" 2>&1
}
# First pass links only tinypsa, to learn which entry points the suite wants.
/usr/bin/libtool -static -o "$out/libtinypsa_all.a" $libs 2>/dev/null
build || true
missing=$(grep -oE '"_psa_[a-z0-9_]+"' "$out/build.log" | sed 's/^"_//; s/"$//' | sort -u || true)
{
	echo "/* Generated by run.sh: PSA calls tinypsa does not provide. */"
	for f in $missing; do echo "int $f(void) { return -134; /* PSA_ERROR_NOT_SUPPORTED */ }"; done
} >"$out/stubs.c"
/usr/bin/cc -c "$out/stubs.c" -o "$out/stubs.o"
/usr/bin/libtool -static -o "$out/libtinypsa_all.a" $libs "$out/stubs.o" 2>/dev/null
build
exe=$out/build/psa-arch-tests-crypto
echo "stubbed: $(echo $missing | wc -w | tr -d ' ') functions"
"$exe"
